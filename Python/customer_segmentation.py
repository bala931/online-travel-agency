def load_dataset():
    """Load the master dataset and keep only Confirmed bookings for RFM."""
    path = os.path.join("Dataset", "ota_master_dataset.csv")
    df = pd.read_csv(path, parse_dates=["Booking_Date", "Checkin_Date", "Checkout_Date"])
    print(f"Master dataset loaded: {df.shape}")
    # Only use Confirmed bookings to compute genuine revenue-generating behaviour
    df_conf = df[df["Booking_Status"] == "Confirmed"].copy()
    print(f"Confirmed bookings for RFM: {len(df_conf):,}")
    return df, df_conf

# ─────────────────────────────────────────────
# STEP 2 — COMPUTE RFM METRICS
# ─────────────────────────────────────────────
def compute_rfm(df_conf):
    """
    Recency  : Days since the customer's most recent Booking_Date,
               measured from the analysis reference date (last date in dataset).
    Frequency: Total number of confirmed bookings by this customer.
    Monetary : Total Net_Revenue generated by this customer (confirmed bookings only).
    """
    # Reference date = day after the last booking date in the dataset
    reference_date = df_conf["Booking_Date"].max() + pd.Timedelta(days=1)
    print(f"RFM Reference Date: {reference_date.date()}")

    rfm = df_conf.groupby("Customer_ID").agg(
        Last_Booking_Date=("Booking_Date", "max"),
        Frequency=("Booking_ID", "count"),
        Monetary=("Net_Revenue", "sum"),
        # Extra enrichment fields
        First_Booking_Date=("Booking_Date", "min"),
        Avg_Review_Score=("Review_Score", "mean"),
        Total_Nights=("Nights", "sum"),
        Avg_Lead_Time=("Lead_Time", "mean"),
        Most_Used_OTA=("OTA_Name", lambda x: x.mode()[0]),
        Most_Booked_Room=("Room_Type", lambda x: x.mode()[0]),
        Most_Used_Device=("Device_Type", lambda x: x.mode()[0]),
    ).reset_index()

    rfm["Recency"] = (reference_date - rfm["Last_Booking_Date"]).dt.days
    rfm["Customer_Lifespan_Days"] = (rfm["Last_Booking_Date"] - rfm["First_Booking_Date"]).dt.days
    rfm["Avg_Revenue_Per_Booking"] = (rfm["Monetary"] / rfm["Frequency"]).round(2)
    rfm["Monetary"] = rfm["Monetary"].round(2)
    rfm["Avg_Review_Score"] = rfm["Avg_Review_Score"].round(2)
    rfm["Avg_Lead_Time"] = rfm["Avg_Lead_Time"].round(1)

    # Bring in demographic info (latest record per customer)
    from_master = pd.read_csv(os.path.join("Dataset", "dim_customers.csv"))
    rfm = rfm.merge(from_master[["Customer_ID","Customer_Name","Age","Gender",
                                  "Country","Loyalty_Status"]], on="Customer_ID", how="left")

    print(f"RFM table: {rfm.shape[0]} unique customers")
    return rfm, reference_date

# ─────────────────────────────────────────────
# STEP 3 — SCORE R, F, M (1–5 QUINTILES)
# ─────────────────────────────────────────────
def assign_rfm_scores(rfm):
    """
    Scoring rules:
    • Recency  : Lower days = better → score 5 for most recent (reverse qcut)
    • Frequency: Higher count = better → score 5 for most frequent
    • Monetary : Higher spend = better → score 5 for highest spender
    Ties are handled with 'first' rank to avoid duplicate bin edges.
    """
    # Recency — inverted (lower recency = higher score)
    rfm["R_Score"] = pd.qcut(rfm["Recency"].rank(method="first"),
                              q=5, labels=[5, 4, 3, 2, 1]).astype(int)

    # Frequency
    rfm["F_Score"] = pd.qcut(rfm["Frequency"].rank(method="first"),
                              q=5, labels=[1, 2, 3, 4, 5]).astype(int)

    # Monetary
    rfm["M_Score"] = pd.qcut(rfm["Monetary"].rank(method="first"),
                              q=5, labels=[1, 2, 3, 4, 5]).astype(int)

    # Combined RFM Score string (e.g., "545")
    rfm["RFM_Score"] = (rfm["R_Score"].astype(str) +
                        rfm["F_Score"].astype(str) +
                        rfm["M_Score"].astype(str))

    # Composite numeric score (sum of R+F+M, range 3–15)
    rfm["RFM_Total"] = rfm["R_Score"] + rfm["F_Score"] + rfm["M_Score"]

    return rfm

