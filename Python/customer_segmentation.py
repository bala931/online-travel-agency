    rfm_r = rfm.copy()
    rfm_r["Recency_inv"]    = 1 - (rfm_r["Recency"] - rfm_r["Recency"].min()) / \
                                   (rfm_r["Recency"].max() - rfm_r["Recency"].min())
    rfm_r["Monetary_norm"]  = (rfm_r["Monetary"] - rfm_r["Monetary"].min()) / \
                               (rfm_r["Monetary"].max() - rfm_r["Monetary"].min())
    rfm_r["Frequency"]      = (rfm_r["Frequency"] - rfm_r["Frequency"].min()) / \
                               (rfm_r["Frequency"].max() - rfm_r["Frequency"].min())
    rfm_r["Total_Nights"]   = (rfm_r["Total_Nights"] - rfm_r["Total_Nights"].min()) / \
                               (rfm_r["Total_Nights"].max() - rfm_r["Total_Nights"].min())
    rfm_r["Avg_Review_Score"] = (rfm_r["Avg_Review_Score"] - rfm_r["Avg_Review_Score"].min()) / \
                                 (rfm_r["Avg_Review_Score"].max() - rfm_r["Avg_Review_Score"].min())

    seg_profiles = rfm_r.groupby("Segment")[metrics].mean()

    N      = len(metrics)
    angles = np.linspace(0, 2*np.pi, N, endpoint=False).tolist()
    angles += angles[:1]  # close polygon

    labels_clean = ["Recency\n(Inverted)", "Frequency\n(Norm)",
                    "Monetary\n(Norm)", "Review\nScore", "Total\nNights"]

    fig, axes = plt.subplots(1, len(available), figsize=(5*len(available), 5),
                             subplot_kw=dict(polar=True))
    if len(available) == 1:
        axes = [axes]

    radar_colors = [SEGMENT_COLORS.get(s, PALETTE["accent1"]) for s in available]

    for ax, seg, col in zip(axes, available, radar_colors):
        if seg not in seg_profiles.index:
            continue
        vals = seg_profiles.loc[seg, metrics].tolist()
        vals += vals[:1]

        ax.set_facecolor(PALETTE["card"])
        ax.plot(angles, vals, color=col, lw=2.5)
        ax.fill(angles, vals, color=col, alpha=0.3)
        ax.set_xticks(angles[:-1])
        ax.set_xticklabels(labels_clean, fontsize=8, color=PALETTE["text"])
        ax.set_yticklabels([])
        ax.set_title(seg, fontweight="bold", fontsize=11, pad=15,
                     color=SEGMENT_COLORS.get(seg, PALETTE["text"]))
        ax.grid(color=PALETTE["grid"], alpha=0.5)
        ax.spines["polar"].set_color(PALETTE["grid"])

    title_bar(fig, "Segment Profile Radar Charts",
              "Normalised R/F/M + Review + Nights per segment")
    fig.tight_layout(rect=[0, 0, 1, 0.93])
    save_fig(fig, "20_radar_profiles.png")

