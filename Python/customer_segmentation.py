# ── CHART 1: Segment distribution (count & revenue share) ──
def chart_segment_overview(rfm):
    seg_stats = rfm.groupby("Segment").agg(
        Customers=("Customer_ID", "count"),
        Total_Revenue=("Monetary", "sum"),
        Avg_Monetary=("Monetary", "mean"),
    ).reset_index().sort_values("Total_Revenue", ascending=False)

    fig = plt.figure(figsize=(22, 9))
    gs  = gridspec.GridSpec(1, 2, figure=fig, wspace=0.35)

    # Left: Stacked horizontal bar (% customer share vs % revenue share)
    ax1 = fig.add_subplot(gs[0])
    total_c = seg_stats["Customers"].sum()
    total_r = seg_stats["Total_Revenue"].sum()
    seg_stats["Cust_%"] = seg_stats["Customers"] / total_c * 100
    seg_stats["Rev_%"]  = seg_stats["Total_Revenue"] / total_r * 100

    y     = np.arange(len(seg_stats))
    h     = 0.35
    colors = [SEGMENT_COLORS.get(s, PALETTE["accent1"]) for s in seg_stats["Segment"]]
