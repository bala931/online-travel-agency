# ── CHART 3: Recency, Frequency, Monetary distributions ──
def chart_rfm_distributions(rfm):
    fig, axes = plt.subplots(1, 3, figsize=(21, 7))
    metrics = [
        ("Recency",   "Days Since Last Booking",  PALETTE["accent2"], False),
        ("Frequency", "Number of Bookings",        PALETTE["accent3"], False),
        ("Monetary",  "Total Net Revenue (USD)",   PALETTE["accent1"], False),
    ]

    for ax, (col, xlabel, color, _) in zip(axes, metrics):
        data = rfm[col].dropna()
        n, bins, patches = ax.hist(data, bins=35, color=color,
                                   edgecolor=PALETTE["bg"], alpha=0.8, density=True)
        kde_x = np.linspace(data.min(), data.max(), 300)
        kde   = gaussian_kde(data)
        ax.plot(kde_x, kde(kde_x), color="white", lw=2, linestyle="--", label="KDE")

        ax.axvline(data.mean(),   color=PALETTE["accent2"], lw=1.8, linestyle="-",
                   label=f"Mean: {data.mean():,.1f}")
        ax.axvline(data.median(), color=PALETTE["accent3"], lw=1.8, linestyle=":",
                   label=f"Median: {data.median():,.1f}")

        ax.set_xlabel(xlabel)
        ax.set_ylabel("Density")
        ax.set_title(col, fontweight="bold", fontsize=14)
        ax.legend(fontsize=8.5)
        ax.grid(True, alpha=0.3)

    title_bar(fig, "RFM Metric Distributions",
              "Histogram + KDE with mean (red) and median (green) markers")
    fig.tight_layout(rect=[0, 0, 1, 0.93])
    save_fig(fig, "17_rfm_distributions.png")

