    ax1.barh(y - h/2, seg_stats["Rev_%"],  h, color=colors, alpha=1.0,  label="Revenue Share %",  edgecolor=PALETTE["bg"])
    ax1.set_yticks(y)
    ax1.set_yticklabels(seg_stats["Segment"], fontsize=9)
    ax1.set_xlabel("Share (%)")
    ax1.set_title("Customer vs Revenue Share by Segment", fontweight="bold")
    ax1.legend(fontsize=9)
    ax1.grid(axis="x", alpha=0.3)

    # Right: Bubble plot — Customers × Avg Revenue, sized by Total Revenue
    ax2 = fig.add_subplot(gs[1])
    bubble_colors = [SEGMENT_COLORS.get(s, PALETTE["accent1"]) for s in seg_stats["Segment"]]
