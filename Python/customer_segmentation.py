def assign_segments(rfm):
    """Map each RFM_Score string to a business segment."""
    rfm["Segment"] = rfm["RFM_Score"].map(SEGMENT_MAP)

    # Catch-all for any unmapped combinations using RFM_Total thresholds
    def fallback_segment(row):
        if pd.notna(row["Segment"]):
            return row["Segment"]
        total = row["RFM_Total"]
        r = row["R_Score"]
        if total >= 12:
            return "Champions"
        elif total >= 10:
            return "Loyal Customers"
        elif total >= 8 and r >= 4:
            return "Potential Loyalists"
        elif total >= 8:
            return "Need Attention"
        elif r >= 4:
            return "Recent Customers"
        elif r <= 2 and total >= 8:
            return "At Risk"
        elif r <= 2 and total >= 5:
            return "Hibernating"
        elif total <= 4:
            return "Lost"
        else:
            return "About to Sleep"

    rfm["Segment"] = rfm.apply(fallback_segment, axis=1)
    return rfm

