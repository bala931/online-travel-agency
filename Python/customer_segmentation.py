def print_summary(rfm):
    print("\n" + "="*62)
    print("  RFM SEGMENTATION — BUSINESS SUMMARY")
    print("="*62)
    seg_summary = rfm.groupby("Segment").agg(
        Customers   = ("Customer_ID",  "count"),
        Pct_Cust    = ("Customer_ID",  lambda x: f"{len(x)/len(rfm)*100:.1f}%"),
        Total_Rev   = ("Monetary",     "sum"),
        Avg_Rev     = ("Monetary",     "mean"),
        Avg_Recency = ("Recency",      "mean"),
        Avg_Freq    = ("Frequency",    "mean"),
        Avg_M_Score = ("M_Score",      "mean"),
    ).sort_values("Total_Rev", ascending=False)

    seg_summary["Rev_Share"] = (seg_summary["Total_Rev"] /
                                seg_summary["Total_Rev"].sum() * 100).round(1)
    seg_summary["Total_Rev"]   = seg_summary["Total_Rev"].round(2)
    seg_summary["Avg_Rev"]     = seg_summary["Avg_Rev"].round(2)
    seg_summary["Avg_Recency"] = seg_summary["Avg_Recency"].round(1)
    seg_summary["Avg_Freq"]    = seg_summary["Avg_Freq"].round(2)

    print(seg_summary.to_string())
    print(f"\nTotal Net Revenue (Confirmed Bookings): ${rfm['Monetary'].sum():,.2f}")
    print(f"Avg Customer Lifetime Value (CLV)     : ${rfm['Monetary'].mean():,.2f}")
    print(f"Median Booking Frequency              : {rfm['Frequency'].median():.0f}")

