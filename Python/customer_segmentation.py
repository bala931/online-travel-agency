def export_rfm(rfm):
    output_cols = [
        "Customer_ID", "Customer_Name", "Age", "Gender", "Country", "Loyalty_Status",
        "First_Booking_Date", "Last_Booking_Date", "Customer_Lifespan_Days",
        "Recency", "Frequency", "Monetary",
        "R_Score", "F_Score", "M_Score", "RFM_Score", "RFM_Total",
        "Segment", "Avg_Revenue_Per_Booking", "Total_Nights",
        "Avg_Lead_Time", "Avg_Review_Score",
        "Most_Used_OTA", "Most_Booked_Room", "Most_Used_Device",
    ]
    rfm_out = rfm[output_cols].copy()
    rfm_out["First_Booking_Date"] = rfm_out["First_Booking_Date"].dt.strftime("%Y-%m-%d")
    rfm_out["Last_Booking_Date"]  = rfm_out["Last_Booking_Date"].dt.strftime("%Y-%m-%d")
    path = os.path.join("Dataset", "rfm_segments.csv")
    rfm_out.to_csv(path, index=False)
    print(f"\nExported: {path}  ({rfm_out.shape[0]} customers, {rfm_out.shape[1]} columns)")
    return rfm_out

